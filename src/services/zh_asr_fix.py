# -*- coding: utf-8 -*-
"""ASR 中文游戏词同音/形近误听纠错（v0.2.21）。

真机 实测
-------------------
    我说   「别玩你的冥狙了」
    屏幕上 「别往你的民居了」

两层错：ASR 把游戏黑话听成普通词（冥狙→民居）；音近（玩→往）。

修在哪一层
----------
  · **不**修在翻译之后（拿译文猜原文，会误伤且错两次）
  · **不**修在云端 prompt（换模型/改 prompt 是死路，本项目实测过）
  · 修在 **ASR 输出后、本地表/云端之前**：输入还是那句话，
    只是把明显的同音错字归一，后面整条链拿到的就是对的词 —— 一处修，全链受益

为什么不用引擎的 `_fix_accent`
------------------------------
那套是针对**英文**的（候选长度不得比原词长 1 个字母）。
中文两字词套不上。「民居→冥驹」是词表级知识，用表不靠猜。

★ 第一版的设计错误（自己踩的，值得记）
--------------------------------------
我给每条规则写了 `ctx`（上下文），但**忘了给 ctx 加括号**：

    ctx = '(换|拿|掉|...|掉了).{0,3}$|吗|呢|吧|了|的|枪'
    pat = re.compile(re.escape('民居') + ctx)     # ← 错

`|` 是**顶层交替**，整个正则变成
    `民居(...)` 或 `吗` 或 `了` 或 `的` 或 `枪`
于是句里**任意一个**「了/的/枪」都被替换成「冥驹」，
而 `m.group(0)[len(k):]` 对单个字取切片得到空串。
实测「别玩你的冥狙了」被吃成「别玩你冥驹冥冥驹冥驹」。

教训：**局部规则的组合必须自己加括号**。Python 不替你加 ——
它把 `a|b` 解释成「a 或 b」，而我心里想的是「(a 或 b) 跟在键后面」。
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 误听 -> 官方名。官方名以 agents.WEAPONS 为唯一来源（项目约定）。
#
# 分两类，**误伤面完全不同**：
#   ① 不可能是正常词的（民巨/明居/冥距/芒侠/盲侠/蟒侠/飞酱/狂土/旷徒/戊卫/鹰影）
#      —— 直接替换，无风险。
#   ② 本身可能是正常词的（民居/护卫/警长）
#      —— **必须**带 ctx，且 ctx 会被强制包进 `(?:...)`。
#
# `why` 是依据，必须写；没有依据的不收（宁缺毋滥）。
# ---------------------------------------------------------------------------

# ① 不可能成词 —— 直接替换
#    ★ 值必须是**单元素 dict**，不能写成 `"冥驹", "why": ...` ——
#      那样 Python 会把它当 tuple（"冥驹", "why"），下游拿到的就是碎片。
#      这个错是守护 audit_zh_asr_fix 抓出来的，不是想出来的。
DIRECT = {
    "民巨": ("冥驹", "狙/巨 同音（狙-居-巨 常见误听链）"),
    "明居": ("冥驹", "冥/明 同音；驹/居 形近"),
    "明狙": ("冥驹", "同音异写（明/冥）"),
    "民狙": ("冥驹", "同音异写（民/冥）"),
    "冥距": ("冥驹", "驹/距 形近同音"),
    "冥狙": ("冥驹", "狙/驹 同音；社区俗称「冥狙」"),
    "芒侠": ("莽侠", "莽/芒 形近"),
    "盲侠": ("莽侠", "莽/盲 形近同音"),
    "蟒侠": ("莽侠", "莽/蟒 形近同音"),
    "飞酱": ("飞将", "将/酱 形近同音"),
    "狂土": ("狂徒", "徒/土 同音"),
    "旷徒": ("狂徒", "狂/旷 形近同音"),
    "戊卫": ("戍卫", "戍/戊 形近"),
}

# ② 本身可能是正常词 —— 必须带上下文
#
# ★ ctx 的方向：**在误听词的【前面】**。
#   我第一版把 ctx 写在后面（`民居(?:枪|了|…)`），于是
#   「他换民居了吗」能命中（换在前面却不匹配）而被我判 FAIL，
#   「他看民居了吗」反而命中 —— 因为后面跟着「了吗」。
#   语义上：到底是枪还是房子，看**动词**（换/拿/有/用）才知道，
#   「他看民居」里的「看」正是房屋义。所以 ctx 要匹配动词。
#
#   为什么删掉「了/吗/呢/吧」这类**语气助词**：
#   「他看民居了吗」有「了吗」但不是枪 —— 语气助词不携带语义。
#   只保留**有语义**的标记：动词 + 「你的/他那把」这类指代 + 明确否定。
#
#   ctx 会被强制包进 (?:...)；空 ctx 一律视为配置错误（见模块载入时）。
CONTEXT = {
    "民居": ("冥驹",
             "真机 实测：ASR 把「冥狙」听成「民居」",
             r"(?:换|拿|用|有|要|买|摸|捡|掉|丢|给|掉给|拿着)"
             r"(?:了|个|一把|一把枪)?\s*"),
    "鹰影": ("幻影",
             "幻/鹰 音近（部分方言区）",
             r"(?:换|拿|用|有|要|买|给)\s*(?:了|个)?\s*"),
    # 「警长」是 Sheriff 的**社区俗称**（用户自己也会这么说），
    # 所以**不做纠错** —— 那是翻译层的活，不是 ASR 纠错。
    #
    # ★ 「护卫 -> 戍卫」本来在表里，**已按宁缺毋滥删掉**：
    #   「护卫」是完全正常的中文（护卫他 / 护卫舰 / 护卫队），实测 ctx
    #   再怎么收窄都会误伤：「我要护卫他」被改成「我要戍卫他」——
    #   把对的改成鬼话。代价对比：少数「戍卫」被听成「护卫」不修（落云端，
    #   慢 400ms 但不错）≪ 正常中文被改坏。按用户最高判据选后者。
    # 「警长」「民居」同理要慎，这就是为什么这张表这么小。
}

# 音近（不是游戏词）：只做**带上下文的整词替换**，不做单字替换 ——
# 「往」是常用字（「往前走」「往来」），单字替换会污染正常句子。
_HOMOPHONE = (("别往你", "别玩你"), ("别往他", "别玩他"))   # 玩/往 同音

OFFICIAL_UNUSED = None

_DIRECT_KEYS = sorted(DIRECT, key=len, reverse=True)
_DIRECT_MAP = {k: v[0] for k, v in DIRECT.items()}
OFFICIAL = set(_DIRECT_MAP.values()) | {v[0] for v in CONTEXT.values()}
_CTX_RULES = []
for _k, (_zh, _why, _ctx) in CONTEXT.items():
    if not _ctx.strip():
        raise ValueError("CONTEXT[%r] 的 ctx 为空 —— 会误伤正常词，必须写上下文" % _k)
    # ★ 三个要点（每一条都对应踩过的坑）：
    #   ① (?:...) 包裹 ctx —— 否则 | 是**顶层交替**，句里任意一个
    #      「了/的/枪」都会被替换（第一版把整句吃成「别玩你冥驹冥冥驹冥驹」）。
    #   ② 上下文在误听词的**左边**，且只匹配**动词/指代**这类有语义的标记；
    #      语气助词「了吗呢吧」不携带语义，纳入会让「他看民居了吗」被误改。
    #   ③ 不用 (?<=...) —— Python 不支持变长 lookbehind（`\s*` 会直接报错）。
    #      改用捕获组定位：匹配 = ctx + key，替换时按 group(1) 的偏移保留前缀。
    _CTX_RULES.append(
        (re.compile("(?:" + _ctx + ")(" + re.escape(_k) + ")"), _k, _zh))
_CTX_RULES.sort(key=lambda r: len(r[1]), reverse=True)


def fix_asr_zh(text: str) -> str:
    """ASR 中文输出纠错（翻译链之前调）。

    只处理**有依据**的误听；本身可能是正常词的（民居/护卫）必须上下文成立。
    """
    if not text:
        return text
    out = text
    for wrong, right in _HOMOPHONE:
        out = out.replace(wrong, right)
    for k in _DIRECT_KEYS:
        out = out.replace(k, _DIRECT_MAP[k])
    for pat, k, zh in _CTX_RULES:
        def _rep(m, _zh=zh):
            # 按 group(1) 在匹配中的偏移保留前缀（动词），只换掉误听词
            pre = m.group(0)[:m.start(1) - m.start(0)]
            return pre + _zh
        out = pat.sub(_rep, out)
    return out