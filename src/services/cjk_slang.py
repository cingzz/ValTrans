# ---------------------------------------------------------------------------
# 语言检测
# ---------------------------------------------------------------------------

_KANA = re.compile(r"[\u3040-\u309f\u30a0-\u30ff\uff66-\uff9f]")
_HANGUL = re.compile(r"[\uac00-\ud7af\u1100-\u11ff\u3130-\u318f]")
_ROMA_HINT = re.compile(
    r"(?:seupaikeu|seolchi|haeje|rote|keullieo|peullaeshi|seumokeu|"
    r"piking|deobeul|reoking|peull|dongmu|wikgu|wkwk|grass)",
    re.I,
)


def detect_lang(text: str) -> str:
    """返回 'ja' / 'ko' / ''（'' = 不是日韩）。"""
    if _HANGUL.search(text):
        return "ko"
    if _KANA.search(text):
        return "ja"
    if _ROMA_HINT.search(text):
        return "ko"
    return ""


