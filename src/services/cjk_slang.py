# 日文假名（ひらがな + カタカナ）。中文译文里**永远不该出现**。
_KANA_RE = re.compile(r"[\u3040-\u30ff\u31f0-\u31ff]")


def _cjk_incomplete(res: str) -> bool:
    """输出里还剩假名 -> 说明有一整块没翻完。

    为什么用假名当判据，而不是「残留谚文/汉字」：
      · 假名 100% 是日语独有，中文里不会出现 -> 判据绝对可靠
      · 汉字不行：「敵」「解除」「天井」在中文里都是合法字形，
        肉眼扫不出来，但它们是**日语用法**（简体对应「敌」「拆」「天」）
    比例阈值取 0.15：留一点余量给「专有名词里本来就带假名」的情况，
    但整句只要还有成片假名就一定判失败。
    """
    if not res:
        return True
    kana = len(_KANA_RE.findall(res))
    letters = len(_KANA_RE.findall(res)) + len(
        re.findall(r"[\u4e00-\u9fff\uac00-\ud7af]", res))
    if not letters:
        return False
    return kana / letters > 0.15


def _replace_longest(text: str, rules: list[tuple[str, str]], lang: str,
                     table: str = "") -> tuple[str, bool]:
    """最长优先逐条替换；替换后剥掉粘连的谓词尾巴。

    `table` 给了就**只替换有担保的条目**（见 provenance.py）：
    用户质问「语法正确的垃圾你也检查不了」——对，机械检查拦不住。
    真正的判据是「有没有人担保」，不是「格式对不对」。
    没担保的条目宁可放过让它落云端整句翻：慢 400~800ms，
    但不会把一条错译钉成「永远且更快」的本地答案。
    """
    out = text
    hit = False
    covered = 0                      # 被替换掉的**原文**字符数
    for src, dst in rules:
        if src not in out:
            continue
        # v0.2.11：**空译文一律跳过**。dst 为空时下面会把 src 直接抹掉，
        # 输出变成「Sounds good」->「 good」——句子看着完整，少了个词，
        # 比翻错更难被发现。宁可这一条不替换（留原文落云端整句翻）。
        if not str(dst).strip():
            continue
        if table and not provenance.is_verified(table, src):
            continue
        # 把词根后面的尾巴一起吃掉
        pat = re.compile(re.escape(src) + r"([^\s]{0,6})")
        m = pat.search(out)
        tail = _strip_tail(m.group(1), lang) if m else ""
        covered += len(src)
        out = out[:m.start()] + dst + tail + out[m.end():]
        hit = True
    # v0.2.11 第7批：**「碰巧替换到一个词」不等于「译完了」**
    #
    # 实测 28 条泄漏（未担保的词条照样出结果），全在日韩侧：
    #     スパイク解除(拆包) -> '包解除。'   意思都错了
    #     스모크 줘(给我烟)   -> '烟给我。'   电报体
    #     미드 플랭크 두 명 -> '绕后两个。'
    # 成因：日韩词表 80%+ 没担保，所以会出现
    # 「已担保的词翻掉了、没担保的原样留着」的**半成品**，
    # 而 `hit=True` 只要求「替换过至少一个词」。
    # 担保闸门拦住了「错译」，却没拦住「半成品」——
    # 跟 local_rules 里 `_EXTRA2` 那个漏洞是同一个出口。
    #
    # 判据改为**覆盖率**：原文里被替换掉的比例太低就当没译完。
    # 阈值 0.6 是实测定的：0.5 会把「미드 스모크」这类两词都覆盖的
    # 正常句子误杀（虽然它们本来也没担保），1.0 又太松。
    if hit:
        _total = len(re.sub(r"\s", "", text))
        if _total and covered / _total < 0.6:
            return out, False          # 半成品，不算命中 -> 落云端
    return out, hit


def _tidy(s: str) -> str:
    # 相邻短语重复（"包点包点清了" -> "包点清了"）
    s = re.sub(r"([\u4e00-\u9fff]{2,4})[\s]*\1", r"\1", s)
    # v0.2.11：中文之间的空格要去掉。
    # 逐词替换天然留空格（"重生 马上" / "烟 中路"），浮窗里显示成
    # 「重生 马上」很别扭 —— 中文没有词间空格的习惯。
    s = re.sub(r"(?<=[\u4e00-\u9fff])[ \t]+(?=[\u4e00-\u9fff])", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"^[\s,.:;!?、，。：；！？]+", "", s)
    s = re.sub(r"[\s,.:;!?、，。：；！？]{2,}", "，", s)
    s = re.sub(r"[\s,.:;!?、，。：；！？]+$", "", s)
    if not s:
        return ""
    if s[-1] not in "。！？!?，,":
        s += "。"
    return s


# ---------------------------------------------------------------------------
# 云端译文的外文残留清洗（v0.2.11）
# ---------------------------------------------------------------------------
# 用户要求：「韩语偶有残留，一定要把它给搞好」。
#
# 实测症状：云端把「리스폰 곧이에요」翻成「리스폰 马上到」——
# 整句翻对了，但把游戏专有名词**原样留在了中文里**。
# 玩家看到中韩混排的字幕是懵的（「리스폰」在国服根本不是词）。
#
# 为什么能零成本修：
#   翻译日/韩→中文用的 KO_RULES / JA_RULES 是 `(外语, 中文)` 对，
#   **方向正好反过来就能用来清洗残留** —— 同一份表、同一份维护，
#   不需要第二份「残留词典」（项目铁律：固定名词单一来源）。
#
# 为什么不在云端重试一次：
#   一次云端往返 400~800ms，而残留修正只需要 0ms 字符串替换。
#   实时字幕场景下为了一处残留再等半秒，不划算。

# ★ v0.2.16：残留清洗用的这两套**不能**再叫 _HANGUL/_KANA——
#   同名重定义会把文件头 detect_lang 用的那套遮蔽掉（后定义胜出），
#   半角假名 \uff66-\uff9f 因此不再判日语、整句落云端。
#   各自起名，detect_lang 的语义恢复为文件头的定义。
_RESID_HANGUL = re.compile(r"[\uac00-\ud7af\u1100-\u11ff\u3130-\u318f]+")
_RESID_KANA = re.compile(r"[\u3040-\u30ff\u31f0-\u31ff\uff66-\uff9f]+")

# 句中助词（非锚定）。`_KO_TAIL` 是 `^` 锚定的，只剥**跟在已识别词根后面**的；
# 而清洗残留时助词出现在句子中间（"中路에서 等着"），锚定版剥不到。
# 两份用途不同、不能合并：合并成非锚定会让 _replace_longest 把正常词也剥坏。
_KO_PARTICLE = re.compile(
    r"(?:에서|에게|으로|으론|까지|부터|한테|께|이랑|랑|하고)")


def _residual_terms(text: str) -> tuple[list[str], list[str]]:
    """列出译文里还残留的外文词（韩文 / 日文假名）。"""
    ko = _RESID_HANGUL.findall(text)
    ja = _RESID_KANA.findall(text)
    # 「重生点」里若混了假名，两边都会收，去重
    seen: dict[str, None] = {}
    for t in ko + ja:
        seen.setdefault(t, None)
    return list(seen), []


def scrub_residual_cjk(out: str) -> tuple[str, list[str], list[str]]:
    """把译文里漏翻的日/韩词换成中文。

    返回 ``(清洗后文本, 已换掉的词, 表里没有的词)``。

    - **已换掉的词**：直接被 KO_RULES / JA_RULES 覆盖，无需人工介入。
    - **表里没有的词**：词表缺条目（可据此补表），原样保留不乱猜 ——
      宁可留一个玩家认得的原词，也不要错译成一个看着像那么回事的词。
    """
    if not out:
        return out, [], []
    residual, _ = _residual_terms(out)
    if not residual:
        return out, [], []

    # 长词优先（一个键是另一个键的前缀时，先换长的）
    fixed = out
    done: list[str] = []
    for src, dst in _KO_IDX + _JA_IDX:
        if src in fixed:
            fixed = fixed.replace(src, dst)
            done.append(src)

    # 残留的**带助词**形式也要剥：清洗器是整串 replace，不像 _replace_longest
    # 那样走一遍 _strip_tail。实测「미드에서」只换掉 미드 会留下
    # 「中路에서」—— 仍然是半中半韩，玩家依旧看不懂。
    # 剥不掉再判为表外词，如实上报而不是乱猜。
    stripped = _KO_PARTICLE.sub("", fixed).strip()
    while stripped != fixed:
        fixed = stripped
        stripped = _KO_PARTICLE.sub("", fixed).strip()
    fixed = re.sub(r"(?<=[\u4e00-\u9fff])[ \t]+(?=[\u4e00-\u9fff])", "", fixed)

    left, _ = _residual_terms(fixed)
    return fixed, done, left


def _clean_phrase(raw: str) -> str:
    """整句表查询（韩语 + 日语）。整串命中（含剥首尾语气词/标点）才返回。

    刻意**不做部分匹配**：宁可这条落回词表/云端，也不要拼出半成品。
    同样走 provenance 闸门：整句表也是手写的，一样可能塞垃圾。
    """
    s = (raw or "").strip().lower()
    for key, zh in _KO_PHRASE_IDX:
        if s == key or s.strip(_PHRASE_PUNCT) == key.strip(_PHRASE_PUNCT):
            if provenance.is_verified("KO_PHRASES", key):
                return _tidy(zh)
    for key, zh in _JA_PHRASE_IDX:
        if s == key or s.strip(_PHRASE_PUNCT) == key.strip(_PHRASE_PUNCT):
            if provenance.is_verified("JA_PHRASES", key):
                return _tidy(zh)
    return ""


def translate_cjk(text: str) -> tuple[str | None, str]:
    """日/韩 -> 中文。命中返回 (译文, 'local')，未命中返回 (None, '')。"""
    raw = (text or "").strip()
    if not raw:
        return None, ""

    # v0.2.11：**整句表优先**（先于词表，也先于语种判定）。
    #
    # 只做整串命中，绝不做部分替换 —— 部分替换就是「刀走。」那种堆词，
    # 需求背景：「不要读得很拗口、看不懂，一定要通顺一点」。
    # 整句没命中就照常走词表 + 整句覆盖判据，覆盖不全仍会退回云端整句翻。
    _ph = _clean_phrase(raw)
    if _ph:
        return _ph, "local"

    lang = detect_lang(raw)

    if lang == "ja":
        res, hit = _replace_longest(raw, _JA_IDX, "ja", "JA_RULES")
        if not hit:
            # 日语玩家大量混用英文黑话（' peek して' / 'rellay して'），
            # 实测这些整句都漏云端。日区用法和英语区一致，复用同一套译法。
            res, hit = _replace_longest(raw.lower(), _JP_JARGON_IDX, "ja",
                                       "_JP_JARGON")
        # 剥句尾动词助动词（前面可能隔着空格：'peek して' -> '架点 して'）
        res = _JA_AUX.sub("", res).strip()
    elif lang == "ko":
        res, hit = _replace_longest(raw, _KO_IDX, "ko", "KO_RULES")
        if not hit:
            # 韩语表没命中，但可能混了罗马音（"seolchi 해줘"）
            res, hit = _replace_longest(raw.lower(), _KR_IDX, "ko", "KO_ROMA")
    else:
        # 无假名/谚文，试罗马音
        res, hit = _replace_longest(raw.lower(), _KR_IDX, "ko")

    # 主表没命中也要跑 laughter（「wkwk」这类纯拉丁串被判成 ko）
    if not hit:
        res, hit = _replace_longest(raw, _LG_IDX, "")
    else:
        res2, hit2 = _replace_longest(res, _LG_IDX, "")
        if hit2:
            res, hit = res2, True

    if not hit:
        return None, ""

    # v0.2.11 第7批：**「碰巧替换到一个词」不等于「译完了」**
    #
    # 词表里大部分词条没担保（日韩担保率 15~20%），所以会出现
    # 「已担保的词翻掉了、没担保的原样留着」的半成品：
    #     スパイク解除 -> スパイク(已担保)->包 / 解除(没担保)->留着
    #                -> '包解除。'  还被当成命中
    # 担保闸门拦住了「错译」，却没拦住「半成品」—— 这是同一个
    # 漏洞的另一个出口（另一个是 local_rules 里的 _EXTRA2）。
    #
    # 判据：输出里还剩假名 = 有一整块没翻完 -> 落云端重翻。
    # **宁可慢 400ms，也不能给玩家看「包解除」。**
    if _cjk_incomplete(res):
        return None, ""

    # 残留外语补扫：日表里混进韩语（敌はuds / "敌は" + 韩语碎词）
    leftover = re.search(r"[\u3040-\u30ff\uac00-\ud7af]", res)
    if leftover:
        res2, hit2 = _replace_longest(res, _KO_IDX + _KR_IDX + _LG_IDX, "ko")
        if hit2:
            res, hit = res2, True

    # 替换后若没有任何实质内容，视为未命中（宁可回退云端）
    if not re.sub(r"[\s\W_]+", "", res):
        return None, ""

    # 【整句覆盖判据】残留源语言文字 = 部分匹配 = 混合语言乱码风险。
    # 只有整句被表内词条覆盖才允许本地返回；否则返回 None 让云端整句翻译
    # （实测「ビーサイト」->「ビー包点」这类半替换输出会毁掉整句，宁慢勿错）。
    if lang == "ja" and _KANA.search(res):
        return None, ""
    if lang == "ko" and _HANGUL.search(res):
        return None, ""
    if lang == "" and re.search(r"[a-z]{3,}", res):
        return None, ""

    out = _tidy(res)
    return (out, "local") if out else (None, "")