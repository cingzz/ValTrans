# 韩语：先长后短
_KO_TAIL = re.compile(
    r"^(?:"
    r" 했습니다|합니다|했어요|했 습니다|입니다|입니다|이에요|예요|에요|"
    r"했지|하겠습니다|합니다|하자|해줘|해줘요|해요|해라|해|한다|한다.?|"
    r"했습니다|하고|하는|한|할|했|이야|예|음|좀|야|요|다|어|고|지|자|"
    r"해준다|해줘봐|하자고|해볼"
    # v0.2.11：韩国语**助词**（조사）。黏着在名词后面，中文里没有对应物。
    # 为什么不逐条补「미드에서」这种整词：
    #   名义 + 助词的组合是**笛卡尔积**，补不完；而它们本来就是同一个语法现象。
    #   加进剥离表后，「미드」这一条自动覆盖 미드에서 / 미드에 / 미드로 / 미드까지…
    #   —— 又是一次「派生优先于枚举」。
    # 刻意不收 은/는/이/가/도/만/나：单字歧义太大
    # （나 既是助词也是「我」，도 既是助词也是「都」，收了会误伤）。
    r"|에서|에게|으로|으론|까지|부터|한테|께|이랑|랑|하고|에게"
    r")+"
)

# 日语：动词/形容词 + 助词尾巴
_JA_TAIL = re.compile(
    r"^(?:"
    r"しました|しています|しない|しないです|してください|した|して|する|します|"
    r"しました|ってる|ている|てる|だった|だっ|でした|ですが|けど|ので|から|に|を|が|は|"
    r"たい|な|ね|よ|か|。"
    r")+"
)

# v0.2.11：日语**名词助词**（非锚定）。
#
# 实测（tests/diag_en_ja.py）日语和韩语踩的是同一个坑，只是形态不同：
#     '敵は' / '敵に' / '敵で' / '味方が'   _JA_TAIL 全部匹配不到
# 原因是 は/が/に/で 混在动词尾巴那条**锚定**规则里，只有整串
# 就是这些助词时才剥得到；跟在名词后面时剥不掉。
# 结果「敵は」换完词剩一个 は，中文里没有这个东西 ->
# 整句覆盖判据判为半匹配 -> 白白退回云端。
#
# 名单词助词一律不入表（は/が/も/の/か 既可能是助词也可能是实词），
# 只收搭配上就无歧义的：は/が 主题主格 · に/で/へ 方向场所 · を 宾格
_JA_PARTICLE = re.compile(
    r"(?:から|まで|して|では|には|へ|に|で|を|と|は|が)")


def _strip_tail(s: str, lang: str) -> str:
    """去掉词根后粘连的尾巴：谓词尾巴 + 日语名词助词。

    日语为什么要单独加 `_JA_PARTICLE`（v0.2.11）：
      `_JA_TAIL` 里虽然列了 は/が/に/で，但那条规则是 `^` 锚定的，
      只有**整串就是**这些助词时才剥得到；跟在名词后面（敵は）就剥不掉。
      结果换完词剩一个 は -> 整句覆盖判据判半匹配 -> 白白退云端。
      实测：敵は / 敵に / 敵で / 味方が 修复前全部剥不掉。
    """
    out = s
    for _ in range(4):                 # 最多剥 4 层（한다+요+다 …）
        pat = _KO_TAIL if lang == "ko" else _JA_TAIL
        new = pat.sub("", out, count=1)
        if lang == "ja":
            new = _JA_PARTICLE.sub("", new, count=1)
        if new == out:
            break
        out = new
    return out


# 日语句尾的**动词助动词**，前面可能有空格（' peek して' -> peek 空格 して）。
# `_JA_TAIL` 是 `^` 锚定的，剥不到句尾；不剥的话 して 会留在译文里，
# 假名残留 -> 整句覆盖判据判半覆盖 -> 退回云端。
_JA_AUX = re.compile(r"(?:\s+(?:して|してね|した|です|ます|だった|だ))\s*$")


