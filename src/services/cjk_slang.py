"""日/韩语音 -> 中文 的本地黑话层（第 1 层，0ms / 0 token）。

背景
----
海外玩家说的不是标准日语/韩语，而是**当地社区黑话 + 英语借词 + 罗马音**的混合体。
云端通用模型（如 Hunyuan-MT）根本不认识这些词：

    日: 「スパイク設置した」 -> 云端常翻成「安装了一个尖刺装置」
    韩: 「스파이크 해제」     -> 云端常翻成「解除尖峰」

这里用本地表把它们直接钉死，保证 0 延迟、100% 准。

黏着语处理
----------
韩/日语都是黏着语，谓词尾巴直接挂在词后：

    스파이크 해제한다   ->  词根「해제」+ 尾巴「한다」
    스파이크 설치했어요  ->  词根「설치」+ 尾巴「했어요」

所以匹配到词根后必须**吃掉尾巴**，否则会翻成「包拆包한다」这种鬼话。
见 `_KO_TAIL` / `_JA_TAIL`。

数据来源
--------
* 日语：日区社区攻略 / スレ 常用口语简写
* 韩语：韩区 naver / arca「발로란트 용어 정리」系列
        （러쉬 / 디폴트 / 리테이크 / 피킹 / 더블피킹 / 점프피킹 / 래킹 / 플 …）
"""

